"""Draft unreviewed eligibility or extractor expectations for the posting corpus."""

from __future__ import annotations

import argparse
import asyncio
import json
from pathlib import Path
from typing import Any

from job_eligibility import EligibilityResponse
from job_eligibility import build_messages as eligibility_messages
from job_eligibility import validate as validate_eligibility
from job_extractor import ExtractionResponse, JobResult
from job_extractor import build_messages as extractor_messages
from job_extractor import validate as validate_extraction
from job_pipeline.llm import LiteLLMCaller, RecordingCaller

ROOT = Path(__file__).resolve().parents[1]
POSTINGS = ROOT / "tests" / "fixtures" / "postings"
_LIST_FIELDS = (
    "responsibilities",
    "required_qualifications",
    "preferred_qualifications",
    "benefits",
)


def _model_key(model: str) -> str:
    return model.replace("/", "__").replace("\\", "__")


def _posting_directories() -> list[Path]:
    if not POSTINGS.is_dir():
        return []
    return sorted(path.parent for path in POSTINGS.glob("*/content.txt"))


def _extractor_directories(directories: list[Path]) -> list[Path]:
    selected: list[Path] = []
    for directory in directories:
        path = directory / "expected_eligibility.json"
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise RuntimeError(f"missing or invalid expectation: {path}") from exc
        if not isinstance(payload, dict) or payload.get("reviewed") is not True:
            raise RuntimeError(f"expectation is not reviewed: {path}")
        if payload.get("decision") != "ineligible":
            selected.append(directory)
    return selected


def _extraction_expectation(result: JobResult) -> dict[str, Any]:
    metadata: dict[str, Any] = {}
    excluded = {*_LIST_FIELDS, "technologies"}
    for name in ExtractionResponse.model_fields:
        if name in excluded:
            continue
        fact = getattr(result, name)
        dumped = fact.model_dump(mode="json")
        metadata[name] = {
            "state": dumped["state"],
            "value": dumped["value"],
        }
    components: dict[str, Any] = {}
    for name in _LIST_FIELDS:
        fact = getattr(result, name)
        values = fact.value or []
        components[name] = [
            item.text if hasattr(item, "text") else item for item in values
        ]
    technologies = [
        {
            "name": technology.canonical or technology.mentions[0].mention,
            "status": technology.status,
        }
        for technology in result.technologies_normalized
    ]
    return {
        "reviewed": False,
        "metadata": metadata,
        **components,
        "technologies": technologies,
        "notes": "Draft generated by a model; operator review is required.",
    }


async def _draft_eligibility(
    directory: Path, caller: LiteLLMCaller, model: str, text: str
) -> None:
    recorder = RecordingCaller(
        caller,
        directory / "responses" / "eligibility",
        key=_model_key(model),
    )
    completion = await recorder.complete(
        eligibility_messages(text), EligibilityResponse
    )
    decision = validate_eligibility(completion.parsed, text)
    expectation = {
        "reviewed": False,
        "decision": decision.decision,
        "must_cite": completion.parsed.evidence,
        "notes": "Draft generated by a model; operator review is required.",
    }
    path = directory / "expected_eligibility.json"
    path.write_text(
        json.dumps(expectation, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


async def _draft_extractor(
    directory: Path, caller: LiteLLMCaller, model: str, text: str
) -> None:
    recorder = RecordingCaller(
        caller,
        directory / "responses" / "extractor",
        key=_model_key(model),
    )
    completion = await recorder.complete(extractor_messages(text), ExtractionResponse)
    result = validate_extraction(completion.parsed, text)
    path = directory / "expected_extraction.json"
    path.write_text(
        json.dumps(
            _extraction_expectation(result),
            indent=2,
            sort_keys=True,
            default=str,
        )
        + "\n",
        encoding="utf-8",
    )


async def _draft(leaf: str, model: str, timeout: float) -> int:
    directories = _posting_directories()
    if not directories:
        raise RuntimeError(f"posting corpus is unavailable: {POSTINGS}")
    if leaf == "extractor":
        directories = _extractor_directories(directories)
    caller = LiteLLMCaller(model, timeout=timeout)
    for directory in directories:
        text = (directory / "content.txt").read_text(encoding="utf-8")
        if leaf == "eligibility":
            await _draft_eligibility(directory, caller, model, text)
        else:
            await _draft_extractor(directory, caller, model, text)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument("--leaf", choices=("eligibility", "extractor"), required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument("--timeout", type=float, default=60.0)
    return parser


def main() -> int:
    args = build_parser().parse_args()
    try:
        return asyncio.run(_draft(args.leaf, args.model, args.timeout))
    except RuntimeError as exc:
        print(exc)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
